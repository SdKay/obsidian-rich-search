import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import fs from 'node:fs';
import { buildEntries, renderGenerated } from './changelog-gen.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
const gen = process.argv[2] === 'generate';

/** Regenerates src/changelog/generated.ts from git tags plus the version in
 *  package.json (see changelog-gen.mjs). Skips, keeping whatever is committed,
 *  when git history isn't usable, e.g. a shallow CI checkout with no tags.
 *
 *  The changelog is committed with the release commit and CI re-checks it, so the
 *  released main.js is exactly what the tagged source builds. Never hand-edit it. */
function generateChangelogMeta() {
	const outPath = 'src/changelog/generated.ts';
	let entries;
	try {
		const pendingVersion = JSON.parse(fs.readFileSync('package.json', 'utf8')).version;
		// The release commit inherits GIT_AUTHOR_DATE, so use it for the pending entry's date.
		const pendingDate = /^\d{4}-\d{2}-\d{2}/.exec(process.env.GIT_AUTHOR_DATE ?? '')?.[0];
		// `npm version` runs this as its lifecycle script: that is the only run allowed to write a first entry.
		const release = process.env.npm_lifecycle_event === 'version';
		entries = buildEntries({ pendingVersion, pendingDate, release, warn: console.warn });
	} catch (err) {
		console.warn(`[changelog] skipping regeneration (${err.message}), keeping existing generated.ts`);
		return;
	}
	fs.mkdirSync('src/changelog', { recursive: true });
	fs.writeFileSync(outPath, renderGenerated(entries));
	console.log(`[changelog] generated.ts updated (${entries.length} versions, latest ${entries[0]?.version ?? 'n/a'})`);
}

if (gen) {
	generateChangelogMeta();
	process.exit(0);
}

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ['src/main.ts'],
	bundle: true,
	// Provided by Obsidian at runtime; bundling a second copy of CodeMirror breaks
	// editor extensions (two different `EditorView` classes never match).
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	generateChangelogMeta();
	await context.rebuild();
	process.exit(0);
} else {
	generateChangelogMeta();
	await context.watch();
}
